def _normalise(name: str) -> str:
    """Case, accents, punctuation and "&" vs "and" never decide a match."""
    plain = unicodedata.normalize("NFKD", name)
    plain = "".join(char for char in plain if not unicodedata.combining(char))
    plain = plain.casefold().replace("&", " and ")
    return " ".join(re.sub(r"[^\w]+", " ", plain).split())


_DISTRIBUTOR_BY_NAME = {_normalise(name): id_ for id_, name in UNIT3D_DISTRIBUTORS}


def unit3d_region_id(region: str) -> int | None:
    """The id of a three-letter region code, or `None` when UNIT3D has none."""
    return UNIT3D_REGION_IDS.get(region.strip().upper())


def unit3d_distributor_id(distributor: str) -> int | None:
    """The id of the distributor the user typed, or `None`.

    An exact name wins. Otherwise the longest listed name the typed one
    starts with, word for word: "Arrow Video" is Arrow, "Criterion
    Collection" is Criterion. A shorter typed name never guesses between
    longer ones ("Warner" is not Warner Bros. or Warner Music).
    """
    typed = _normalise(distributor)
    if not typed:
        return None
    if typed in _DISTRIBUTOR_BY_NAME:
        return _DISTRIBUTOR_BY_NAME[typed]
    words = typed.split()
    for length in range(len(words) - 1, 0, -1):
        found = _DISTRIBUTOR_BY_NAME.get(" ".join(words[:length]))
        if found is not None:
            return found
    return None
