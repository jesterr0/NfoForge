"""Moving the data folder, and the plugins folder, somewhere the user chooses.

Where the folders are is recorded by `paths.write_data_location`. This module
is the part that has to happen first: checking that a destination is somewhere
data can safely go, copying it there, and repointing the settings that name
the old folder by absolute path.

Copied rather than moved. The old folder is still in use by the running
process until it restarts, and a copy that fails half way leaves nothing lost.
The user removes the old folder once they have seen the new one work.
"""

from collections.abc import Callable, MutableMapping, MutableSequence
from enum import Enum, auto
from pathlib import Path
import shutil
import sys
from typing import Any

import tomlkit
from tomlkit.items import String

from nfoforge.backend.utils.working_dir import (
    IS_FROZEN,
    PROCESSING_DIR_NAME,
    WORKSPACE_DIR_NAME,
    asset_root,
    normalise_path,
)
from nfoforge.config.layout_version import LAYOUT_RECORD_NAME
from nfoforge.config.paths import LOCATION_FILE_NAME, AppPaths
from nfoforge.config.persistence import atomic_write_text

Progress = Callable[[str], None]


class RelocationError(Exception):
    """A destination was refused, or the copy did not complete."""


class DataDestination(Enum):
    EMPTY = auto()
    """Nothing there yet, so the current data can be copied in."""

    EXISTING_DATA = auto()
    """Already an NfoForge data folder, so it is used as it is."""


def check_data_destination(paths: AppPaths, destination: Path) -> DataDestination:
    """What choosing `destination` as the data folder would mean.

    Refuses a folder holding anything that is not NfoForge's own data. The
    layout migration runs over a data folder that has no record of its layout,
    and it moves folders it recognises by name -- a `jobs` folder at the root of
    someone's documents would be moved into the workspace.
    """
    _refuse_shared_location(paths, destination, "data folder")
    current = normalise_path(paths.state_root)
    chosen = normalise_path(destination)
    if chosen.is_relative_to(current) or current.is_relative_to(chosen):
        raise RelocationError(
            "The data folder cannot be moved inside itself, or into a folder "
            "that contains it."
        )
    if not destination.is_dir():
        raise RelocationError(f"{destination} is not a folder.")
    if (destination / LAYOUT_RECORD_NAME).is_file():
        return DataDestination.EXISTING_DATA
    if any(destination.iterdir()):
        raise RelocationError(
            f"{destination} already holds other files. Choose an empty folder, "
            "or a folder NfoForge already keeps its data in."
        )
    return DataDestination.EMPTY


def check_plugins_destination(paths: AppPaths, destination: Path) -> None:
    """Refuse a plugins folder that would share a location it must not.

    Unlike the data folder, one already holding files is fine: a folder of
    plugin checkouts is exactly what someone may want to point at, and the
    loader only reads subfolders holding a plugin manifest.
    """
    _refuse_shared_location(paths, destination, "plugins folder")
    if normalise_path(destination) == normalise_path(paths.state_root):
        raise RelocationError(
            "The plugins folder cannot be the data folder itself. Choose a "
            "folder of its own."
        )
    if not destination.is_dir():
        raise RelocationError(f"{destination} is not a folder.")


def _refuse_shared_location(paths: AppPaths, destination: Path, label: str) -> None:
    """Never inside the installation, which a release replaces wholesale.

    Keeping user state out of the installation is the point of having a data
    folder at all, so putting it back there would undo that.
    """
    if not destination.is_absolute():
        raise RelocationError(f"The {label} must be an absolute path.")
    if normalise_path(destination).is_relative_to(_installation()):
        raise RelocationError(
            f"The {label} cannot be inside NfoForge's installation, which is "
            "replaced when you update."
        )


def _installation() -> Path:
    """The folder a release is unpacked into, or the checkout when from source.

    Not derived from `asset_root` in a frozen build, because that sits inside
    PyInstaller's contents folder, one level below what a user would choose.
    """
    if IS_FROZEN:
        return normalise_path(Path(sys.executable).parent)
    return normalise_path(asset_root().parent)


def copy_data(
    source: Path, destination: Path, progress: Progress | None = None
) -> None:
    """Copy the data folder into `destination`, then repoint its settings.

    Run output in the workspace is left behind. It is regenerated by every run
    and can be large, and Clean Up would delete it anyway. Saved jobs are kept,
    because a job owns everything it needs inside its own folder.

    The location file is left behind as well, because it belongs to the
    default per-user directory and not to whichever data folder is in use.
    """
    processing = source / WORKSPACE_DIR_NAME / PROCESSING_DIR_NAME

    def ignored(directory: str, names: list[str]) -> set[str]:
        here = Path(directory)
        skipped: set[str] = set()
        if here == source and LOCATION_FILE_NAME in names:
            skipped.add(LOCATION_FILE_NAME)
        if here == processing.parent and PROCESSING_DIR_NAME in names:
            skipped.add(PROCESSING_DIR_NAME)
        if progress is not None and here.parent == source:
            progress(f"Copying {here.name}")
        return skipped

    try:
        shutil.copytree(source, destination, dirs_exist_ok=True, ignore=ignored)
    except (OSError, shutil.Error) as error:
        raise RelocationError(
            f"Your data could not be copied to {destination}. Nothing was "
            f"changed, and NfoForge is still using {source}.\n\n{error}"
        ) from error

    if progress is not None:
        progress("Updating settings")
    repoint_settings(destination, old_root=source)


def copy_plugins(source: Path, destination: Path) -> None:
    """Copy the user's plugins into an empty plugins folder they chose.

    Only offered for an empty destination, so nothing already there is
    replaced.
    """
    if not source.is_dir():
        return
    try:
        shutil.copytree(source, destination, dirs_exist_ok=True)
    except (OSError, shutil.Error) as error:
        raise RelocationError(
            f"Your plugins could not be copied to {destination}.\n\n{error}"
        ) from error


def repoint_settings(state_root: Path, old_root: Path) -> list[Path]:
    """Rewrite every setting naming a path in `old_root` to the same path here.

    Needed because profiles store absolute paths: the working directory is
    written out in full once a profile is saved, and tools the migration moved
    into the data folder are named by where they landed. Left alone, a copied
    profile would keep using the old folder -- including its saved jobs --
    until the user removed it, and then fail.

    Every string in the document is considered rather than a list of known
    settings, so a setting added later is covered without anyone remembering
    this. Only an absolute path inside `old_root` is changed, which no value
    that does not name something in the data folder can be.

    Rewritten with `tomlkit` so the files keep their comments and ordering.
    Returns the files that changed.
    """
    documents = sorted((state_root / "config" / "profiles").glob("*.toml"))
    documents.append(state_root / "config" / "program.toml")
    old = normalise_path(old_root)

    changed: list[Path] = []
    for document_path in documents:
        if not document_path.is_file():
            continue
        try:
            document = tomlkit.parse(document_path.read_text(encoding="utf-8"))
        except Exception as error:
            # tomlkit raises several unrelated types for a bad document, and a
            # profile that cannot be read cannot be repointed either way.
            raise RelocationError(
                f"{document_path} could not be read, so its paths could not be "
                f"updated: {error}"
            ) from error
        if _repoint(document, old, state_root):
            atomic_write_text(document_path, tomlkit.dumps(document))
            changed.append(document_path)
    return changed


def _same_style(original: str, replacement: str) -> Any:
    """`replacement`, quoted the way the user's file quoted `original`.

    A Windows path is usually written as a literal string so its backslashes
    need no escaping, and assigning a plain `str` would turn every one of them
    into a doubled, escaped string. A literal string cannot hold a single
    quote, so a path with one falls back to the escaped form.
    """
    if isinstance(original, String) and "'" not in replacement:
        quoted = original.as_string()
        if quoted.startswith("'") and not quoted.startswith("'''"):
            return tomlkit.string(replacement, literal=True)
    return replacement


def _repoint(container: Any, old: Path, new: Path) -> bool:
    """Replace, in place, each string in `container` naming a path under `old`."""
    changed = False
    if isinstance(container, MutableMapping):
        keys: Any = list(container.keys())
    elif isinstance(container, MutableSequence):
        keys = range(len(container))
    else:
        return False

    for key in keys:
        value = container[key]
        if isinstance(value, (MutableMapping, MutableSequence)):
            changed |= _repoint(value, old, new)
            continue
        if not isinstance(value, str) or not value.strip():
            continue
        candidate = Path(value)
        if not candidate.is_absolute():
            continue
        resolved = normalise_path(candidate)
        if not resolved.is_relative_to(old):
            continue
        container[key] = _same_style(value, str(new / resolved.relative_to(old)))
        changed = True
    return changed
